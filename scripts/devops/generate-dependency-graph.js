#!/usr/bin/env node
'use strict';
/**
 * Module boundary linter (ADR 0005, AGENTS.md 2.2).
 *
 * Builds the module dependency graph from actual source references and checks it against
 * sfdx-project.json:
 *   1. Layering    - modules may only depend downward (lower numeric prefix).
 *   2. Declaration - every referenced module / external package is a declared dependency.
 *   3. Transitive  - 2GP needs each package's full dependency chain declared explicitly.
 * Unused declared dependencies are reported as warnings.
 *
 * Usage: node scripts/devops/generate-dependency-graph.js [--write docs/architecture/module-dependencies.md]
 * Exits 1 when any violation is found.
 */
const fs = require('node:fs');
const path = require('node:path');
const repo = require('./lib/repo');

function main() {
    const args = process.argv.slice(2);
    const writeIndex = args.indexOf('--write');
    const outputFile = writeIndex === -1 ? null : args[writeIndex + 1];

    const config = repo.loadConfig();
    const modules = repo.loadModules();
    const byName = new Map(modules.map((m) => [m.name, m]));
    const symbols = repo.buildSymbolIndex(modules, config);

    // edges: module -> target -> Set of "file -> symbol" evidence
    const edges = new Map(modules.map((m) => [m.name, new Map()]));
    for (const mod of modules) {
        for (const file of repo.listFiles(mod.path)) {
            if (!/\.(cls|trigger|js|html|xml|json)$/.test(file)) continue;
            for (const ref of repo.extractReferences(file)) {
                const owners = symbols.get(ref);
                if (!owners) continue;
                const ownerNames = [...new Set(owners.map((o) => o.owner))];
                if (ownerNames.includes(mod.name)) continue; // defined locally (incl. same-named fields)
                if (ownerNames.length > 1 && owners.every((o) => o.kind === 'CustomFieldName')) continue; // ambiguous bare field name
                for (const owner of ownerNames) {
                    const targets = edges.get(mod.name);
                    if (!targets.has(owner)) targets.set(owner, new Set());
                    targets.get(owner).add(`${path.relative(mod.path, file)} -> ${ref}`);
                }
            }
        }
    }

    const violations = [];
    const warnings = [];
    for (const mod of modules) {
        const declared = new Set(mod.dependencies);
        for (const [target, evidence] of edges.get(mod.name)) {
            const example = [...evidence].slice(0, 3).join('; ');
            const targetModule = byName.get(target);
            if (targetModule && targetModule.rank >= mod.rank) {
                violations.push(`[layering] ${mod.name} references ${target} (same or higher layer): ${example}`);
            }
            if (!declared.has(target)) {
                violations.push(`[undeclared] ${mod.name} references ${target} without declaring it: ${example}`);
            }
        }
        // 2GP: declared dependencies must include the dependencies of every declared dependency.
        for (const dep of mod.dependencies) {
            for (const transitive of byName.get(dep)?.dependencies || []) {
                if (!declared.has(transitive)) {
                    violations.push(
                        `[transitive] ${mod.name} depends on ${dep} but does not declare its dependency ${transitive}`
                    );
                }
            }
        }
        const used = new Set(edges.get(mod.name).keys());
        const reachableThroughUsed = new Set();
        for (const u of used) (byName.get(u)?.dependencies || []).forEach((d) => reachableThroughUsed.add(d));
        for (const dep of mod.dependencies) {
            if (
                !used.has(dep) &&
                !reachableThroughUsed.has(dep) &&
                repo.profileModules(config, 'full').includes(mod.path)
            ) {
                warnings.push(`[unused] ${mod.name} declares ${dep} but no source references it`);
            }
        }
    }

    const mermaid = renderMermaid(modules, edges);
    if (outputFile) {
        const doc = [
            '# Module Dependency Graph',
            '',
            '> Generated by `npm run audit:deps -- --write docs/architecture/module-dependencies.md`. Do not edit by hand.',
            '',
            'Solid arrows are references found in source; every one must also be declared in `sfdx-project.json`.',
            '',
            '```mermaid',
            mermaid,
            '```',
            ''
        ].join('\n');
        fs.mkdirSync(path.dirname(path.join(repo.ROOT, outputFile)), { recursive: true });
        fs.writeFileSync(path.join(repo.ROOT, outputFile), doc);
        console.log(`Wrote ${outputFile}`);
    }

    console.log('Module dependency graph (observed references):');
    for (const mod of modules) {
        const targets = [...edges.get(mod.name).keys()];
        console.log(`  ${mod.name} -> ${targets.length ? targets.join(', ') : '(none)'}`);
    }
    warnings.forEach((w) => console.log(`WARN  ${w}`));
    violations.forEach((v) => console.error(`ERROR ${v}`));
    if (violations.length) {
        console.error(`\n${violations.length} module boundary violation(s).`);
        process.exit(1);
    }
    console.log('\nModule boundaries OK.');
}

function renderMermaid(modules, edges) {
    const id = (name) => name.replace(/[^A-Za-z0-9]/g, '_');
    const lines = ['graph TD'];
    for (const mod of modules) lines.push(`    ${id(mod.name)}["${mod.name}<br/><small>${mod.path}</small>"]`);
    const externals = new Set();
    for (const targets of edges.values())
        for (const t of targets.keys()) if (!modules.some((m) => m.name === t)) externals.add(t);
    for (const ext of externals) lines.push(`    ${id(ext)}(["${ext}"])`);
    for (const [from, targets] of edges) for (const to of targets.keys()) lines.push(`    ${id(from)} --> ${id(to)}`);
    return lines.join('\n');
}

main();
